#!/usr/bin/env python3
"""Embed a program's icon PNGs into it (piccolo, piccoletto, ...).

Run from the program's repository, with its name:

    python3 deps/common/hosts-common/tools/make_app_icon.py piccoletto

Reads <repo>/assets/branding/png/<name>-icon-<size>.png and writes two files
from the same PNGs:

- src/app_icon.h: the window icon. The header holds the PNG bytes as they
  are; SDL decodes them at start (SDL_LoadPNG_IO, frontends-common's
  app_shell) and hands every size to the window manager as one icon with
  alternate images.
- assets/windows/<name>.ico: the .exe's icon on Windows (Explorer, the
  taskbar, shortcuts), compiled into <name>.exe as a resource
  (src/<name>.rc.in). Its images are the same PNGs, stored as they are (ICO
  files may hold PNGs since Windows Vista).

The PNGs come from the SVGs in assets/branding (rendered with Inkscape, see
that folder's README.md). No dependencies beyond the Python standard library.
"""

import os
import struct
import sys

# The first one is the base image, the rest are alternates. 256 is also the
# largest an ICO entry can say.
SIZES = [256, 128, 64, 48, 32, 24, 16]


def read_png(png_dir, name, size):
    with open(os.path.join(png_dir, "%s-icon-%d.png" % (name, size)), "rb") as f:
        return f.read()


def write_ico(png_dir, name, ico_out):
    # ICONDIR, then one ICONDIRENTRY per image, then the images. Smallest
    # first, as Windows' own icons are.
    images = [(size, read_png(png_dir, name, size)) for size in sorted(SIZES)]
    header = struct.pack("<HHH", 0, 1, len(images))   # reserved, type 1 = icon, count
    offset = len(header) + 16 * len(images)
    entries = b""
    for size, data in images:
        side = 0 if size >= 256 else size   # 0 means 256
        # width, height, palette colors, reserved, planes, bits per pixel, bytes, offset
        entries += struct.pack("<BBBBHHII", side, side, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    os.makedirs(os.path.dirname(ico_out), exist_ok=True)
    with open(ico_out, "wb") as f:
        f.write(header + entries + b"".join(data for _, data in images))
    print("wrote %s" % ico_out)


def write_header(png_dir, name, out):
    lines = []
    lines.append("#pragma once")
    lines.append("")
    lines.append("// Generated by hosts-common's tools/make_app_icon.py from assets/branding/png. Don't edit.")
    lines.append("// (The .exe's icon on Windows comes from the same PNGs: assets/windows/%s.ico.)" % name)
    lines.append("// %s's window icon: PNG files, largest first." % name)
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append('#include "app_shell.h"')
    lines.append("")
    for size in SIZES:
        data = read_png(png_dir, name, size)
        lines.append("static const uint8_t app_icon_png_%d[%d] = {" % (size, len(data)))
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
        lines.append("};")
        lines.append("")
    lines.append("static const AppShellIcon app_icon_images[] = {")
    for size in SIZES:
        lines.append("    {app_icon_png_%d, sizeof(app_icon_png_%d)}," % (size, size))
    lines.append("};")
    lines.append("")
    lines.append("static const int32_t app_icon_image_count = %d;" % len(SIZES))
    lines.append("")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s" % out)


def main():
    if len(sys.argv) != 2:
        print("usage: make_app_icon.py <name>   (run from the program's repository: piccolo, piccoletto)", file=sys.stderr)
        return 1
    name = sys.argv[1]
    root = os.getcwd()
    png_dir = os.path.join(root, "assets", "branding", "png")
    write_ico(png_dir, name, os.path.join(root, "assets", "windows", "%s.ico" % name))
    write_header(png_dir, name, os.path.join(root, "src", "app_icon.h"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
